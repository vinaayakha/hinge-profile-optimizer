// Bundles the skill markdown into src/content.ts so the deployed function needs no filesystem access.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const skillDir = join(here, "..", "..", "skills", "hinge-profile-optimizer");
const refsDir = join(skillDir, "references");

const docs = { skill: readFileSync(join(skillDir, "SKILL.md"), "utf8") };
for (const file of readdirSync(refsDir).filter((f) => f.endsWith(".md")).sort()) {
  docs[file.replace(/\.md$/, "")] = readFileSync(join(refsDir, file), "utf8");
}

writeFileSync(
  join(here, "..", "src", "content.ts"),
  `// Generated by scripts/gen-content.mjs. Do not edit.\nexport const DOCS: Record<string, string> = ${JSON.stringify(docs, null, 2)};\n`
);
console.log("docs:", Object.keys(docs).join(", "));
